// Role: pure string emitters for docs/api/methods.md and docs/api/events.md (generated reference, no timestamps).
// Informs HERDR-ADR-0014 (executable docs) and plan sections 3.2 and 3.6 (emit-docs.ts; events.md facts).
import { CapabilityClass, ENTRY_CLASSES } from './capabilities.ts';
import { methodRows } from './emit-method-table.ts';
import type { MethodRow } from './emit-method-table.ts';
import { entryMethods } from './emit-names.ts';
import { eventFacts, eventMap, NO_VALUE } from './event-map.ts';
import type { EventMapRow } from './event-map.ts';
import { OVERRIDES } from './overrides.ts';
import type { ApiSchema } from './schema.ts';
import { methodParamsName } from './schema.ts';

const UNMAPPED_RESULT = 'unmapped (phase 3)';
const YES = 'yes';
const NO = 'no';
const ROOT_SECTION = 'root';
const GENERATED_NOTE = '<!-- GENERATED by gen/ from schema/herdr-api.schema.json. Do not edit. -->';
const CELL_SEPARATOR = ' | ';
const ROW_OPEN = '| ';
const ROW_CLOSE = ' |';
const TABLE_RULE = '|';

// A Markdown table row from its cells.
function tableRow(cells: readonly string[]): string {
  return `${ROW_OPEN}${cells.join(CELL_SEPARATOR)}${ROW_CLOSE}`;
}

// A Markdown table from a header and rows.
function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const rule = `${TABLE_RULE}${header.map(() => ' --- |').join('')}`;
  return [tableRow(header), rule, ...rows.map(tableRow)].join('\n');
}

function banner(schema: ApiSchema): string {
  return `${GENERATED_NOTE}\n<!-- herdr protocol ${schema.protocol}, schema_version ${schema.schema_version}. -->`;
}

// The first segment of a method, or the root section for a method with no namespace.
function sectionOf(row: MethodRow): string {
  return row.ns[0] ?? ROOT_SECTION;
}

// Methods grouped by section, in the order the schema lists them.
function sections(rows: readonly MethodRow[]): readonly (readonly [string, readonly MethodRow[]])[] {
  const names = [...new Set(rows.map(sectionOf))];
  return names.map((name) => [name, rows.filter((row) => sectionOf(row) === name)] as const);
}

function methodTableRow(schema: ApiSchema, row: MethodRow): readonly string[] {
  const gate = OVERRIDES[row.name]?.capability;
  return [
    `\`${row.name}\``,
    `\`P.${methodParamsName(schema, row.name)}\``,
    row.result === null ? UNMAPPED_RESULT : `\`${row.result}\``,
    row.class,
    row.longPoll ? YES : NO,
    gate ?? NO_VALUE,
  ];
}

const METHOD_HEADER = ['Method', 'Params type', 'Result tag', 'Class', 'Long-poll', 'Gate'] as const;

function classCountRows(rows: readonly MethodRow[]): readonly (readonly string[])[] {
  return Object.values(CapabilityClass).map((cls) => [cls, String(rows.filter((row) => row.class === cls).length)]);
}

function entryMatrixRows(): readonly (readonly string[])[] {
  const classSets: Readonly<Record<string, readonly CapabilityClass[]>> = ENTRY_CLASSES;
  return Object.entries(classSets).map(([key, classes]) => {
    const marks = Object.values(CapabilityClass).map((cls) => (classes.includes(cls) ? YES : NO));
    return [`\`${key}\``, ...marks];
  });
}

// The method reference: one section per namespace, then the class counts and the entry-point matrix.
export function emitMethodsDoc(schema: ApiSchema): string {
  const rows = methodRows(schema);
  const body = sections(rows).map(([name, members]) => `## ${name}\n\n${table(METHOD_HEADER, members.map((row) => methodTableRow(schema, row)))}`);
  const entryHeader = ['Entry', ...Object.values(CapabilityClass)];
  return `${banner(schema)}
# Method reference

${rows.length} methods. Each row gives the wire method, the generated params type, the response tag, the capability class, whether the call is long-poll, and the capability gate.

${body.join('\n\n')}

## Class counts

${table(['Class', 'Methods'], classCountRows(rows))}

## Entry points

Each entry point lists the classes it carries (\`ENTRY_CLASSES\` in gen/capabilities.ts). The prompt entry also carries \`agent.prompt\`.

${table(entryHeader, entryMatrixRows())}

Expanded entry methods: ${entryMethods(schema).map(([key, names]) => `${key} ${names.length}`).join(', ')}.
`;
}

const EVENT_HEADER = ['EventKind', 'Subscription type', 'EventMatch', 'Frame'] as const;

function eventRow(row: EventMapRow): readonly string[] {
  return [
    row.kind === undefined ? NO_VALUE : `\`${row.kind}\``,
    row.subscription === undefined ? NO_VALUE : `\`${row.subscription}\``,
    row.eventMatch ? YES : NO,
    `\`${row.frame}\``,
  ];
}

// The event reference: the join table, then the facts the coverage test asserts.
export function emitEventsDoc(schema: ApiSchema): string {
  const rows = eventMap(schema);
  const facts = eventFacts(rows);
  const list = (names: readonly string[]): string => names.map((name) => `\`${name}\``).join(', ');
  return `${banner(schema)}
# Event reference

${facts.kindCount} event kinds and ${facts.subscriptionCount} subscription types. A subscription type is the event kind with its first \`_\` replaced by \`.\`, except for the parameterised kinds that have no event kind.

${table(EVENT_HEADER, rows.map(eventRow))}

## Facts

- ${facts.notAwaitable.length} kinds are not awaitable with \`events.wait\` (no EventMatch): ${list(facts.notAwaitable)}.
- ${list(facts.notSubscribable)} has no subscription type and is reachable only through \`events.wait\`.
- ${list(facts.noEventKind)} have no EventKind; they carry the parameterised subscription frame.
- \`pane_agent_status_changed\` is in both shapes: the lifecycle EventFrame and the SubscriptionEventFrame.
`;
}
